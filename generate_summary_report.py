import os
import sqlite3
import pandas as pd

DB_NAME = "customer_journey.db"
OUTPUT_REPORT = "output.md"

print("[Info] Generating summary report from database...")

if not os.path.exists(DB_NAME):
    raise FileNotFoundError(
        f"Database {DB_NAME} not found. Please run load_to_sqlite.py first."
    )

conn = sqlite3.connect(DB_NAME)

sessions = pd.read_sql("SELECT * FROM session", conn)
orders = pd.read_sql("SELECT * FROM \"order\"", conn)
events = pd.read_sql("SELECT * FROM journey_event", conn)
ground_truth = pd.read_sql("SELECT * FROM ground_truth", conn)

conn.close()

# Base Metrics
total_sessions = len(sessions)
total_conversions = len(orders)
conversion_rate = (total_conversions / total_sessions) * 100 if total_sessions > 0 else 0
total_events = len(events)
total_anomalies = len(ground_truth)

# Step 11: Derived Metrics Integration
events['event_timestamp'] = pd.to_datetime(events['event_timestamp'])
events['ingestion_timestamp'] = pd.to_datetime(events['ingestion_timestamp'])
events['latency_seconds'] = (events['ingestion_timestamp'] - events['event_timestamp']).dt.total_seconds()
avg_latency = events['latency_seconds'].mean()

session_metrics = events.groupby("session_id").agg(
    duration_sec=("event_timestamp", lambda x: (x.max() - x.min()).total_seconds()),
    last_event=("event_type", "last")
).reset_index()

avg_duration = session_metrics['duration_sec'].mean()

# Identify abandoned sessions for drop-off analysis
converted_sessions = set(orders['session_id'])
session_metrics['outcome'] = session_metrics['session_id'].apply(
    lambda x: 'conversion' if x in converted_sessions else 'abandonment'
)
abandoned = session_metrics[session_metrics['outcome'] == 'abandonment']

drop_off_stages = abandoned['last_event'].value_counts(normalize=True).reset_index()
drop_off_stages.columns = ["Drop-off Stage", "Percentage of Abandonments"]
drop_off_stages["Percentage of Abandonments"] = (drop_off_stages["Percentage of Abandonments"] * 100).round(2).astype(str) + "%"

# Breakdown Tables
anomaly_breakdown = ground_truth["issue_type"].value_counts().reset_index()
anomaly_breakdown.columns = ["Issue Type", "Count"]

channel_breakdown = sessions["channel"].value_counts().reset_index()
channel_breakdown.columns = ["Channel", "Sessions"]

report_content = f"""# Customer Journey Pipeline - Executive Summary Report

## Pipeline Performance Metrics
- **Total Sessions Processed:** `{total_sessions:,}`
- **Total Cross-Channel Events:** `{total_events:,}`
- **Successful Conversions:** `{total_conversions:,}`
- **Funnel Conversion Rate:** `{conversion_rate:.2f}%`
- **Total Isolated Anomalies:** `{total_anomalies:,}`

## Derived Analytics (Step 11 Integration)
- **Average Session Duration:** `{avg_duration:.2f} seconds`
- **Average Ingestion Latency:** `{avg_latency:.2f} seconds`

---

## Top Abandonment Drop-off Stages
{drop_off_stages.head().to_markdown(index=False)}

---

## Channel Distribution
{channel_breakdown.to_markdown(index=False)}

---

## Isolated Anomaly Breakdown (Ground Truth Manifest)
{anomaly_breakdown.to_markdown(index=False)}

---
*Report automatically generated by the Customer Journey Data Engineering Pipeline.*
"""

with open(OUTPUT_REPORT, "w", encoding="utf-8") as f:
    f.write(report_content)

print(f"[Success] Output report generated successfully: {os.path.abspath(OUTPUT_REPORT)}")